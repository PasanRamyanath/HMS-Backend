/**
 * @hms/cdk - export-outputs.mjs
 * Automatically extracts CloudFormation outputs from cdk-outputs.json
 * and writes environment variables to HMS-Frontend/.env.local and .env.production.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

/**
 * @typedef {Object} ExportConfig
 * @property {string} outputsPath
 * @property {string} frontendDir
 * @property {string} region
 */

/**
 * Resolves input and output target directories.
 * @returns {ExportConfig}
 */
function resolveConfig() {
  const customOutputsPath = process.argv[2];
  const candidatePaths = [
    customOutputsPath,
    resolve(process.cwd(), "cdk-outputs.json"),
    resolve(__dirname, "../cdk-outputs.json"),
    resolve(__dirname, "../../../cdk-outputs.json"),
    resolve(__dirname, "../../cdk-outputs.json"),
  ].filter(Boolean);

  const outputsPath =
    candidatePaths.find((p) => p && existsSync(p)) ?? candidatePaths[0] ?? "cdk-outputs.json";
  const frontendDir = resolve(__dirname, "../../../../HMS-Frontend");
  const region = process.env.AWS_REGION ?? process.env.CDK_DEFAULT_REGION ?? "ap-south-1";

  return {
    outputsPath,
    frontendDir,
    region,
  };
}

/**
 * Loads CloudFormation stack outputs safely from JSON file.
 * @param {string} outputsPath
 * @returns {Record<string, string>}
 */
function loadOutputs(outputsPath) {
  if (!existsSync(outputsPath)) {
    return {};
  }

  try {
    const rawContent = readFileSync(outputsPath, "utf-8");
    const parsed = JSON.parse(rawContent);

    const stackOutput =
      parsed.SriLankaHmsStack ??
      parsed.TestSriLankaHmsStack ??
      Object.values(parsed).find((val) => typeof val === "object" && val !== null) ??
      {};

    return typeof stackOutput === "object" && stackOutput !== null ? stackOutput : {};
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`Warning: Failed to parse outputs from ${outputsPath}: ${message}\n`);
    return {};
  }
}

/**
 * Generates frontend environment file lines from stack outputs.
 * @param {Record<string, string>} outputs
 * @param {string} region
 * @returns {string[]}
 */
function generateEnvLines(outputs, region) {
  const graphqlUrl =
    outputs.HmsGraphQLApiUrl ?? "https://mock-appsync.ap-south-1.amazonaws.com/graphql";
  const graphqlApiId = outputs.HmsGraphQLApiId ?? "mock-api-id";
  const userPoolId = outputs.HmsUserPoolId ?? "ap-south-1_mockpool";
  const userPoolClientId = outputs.HmsUserPoolClientId ?? "mockclientid12345";
  const webhooksUrl =
    outputs.WebhooksIngressUrl ?? "https://mock-webhook.lambda-url.ap-south-1.on.aws/";
  const distributionDomain =
    outputs.HmsDistributionDomainName ?? "mock-distribution.cloudfront.net";
  const cloudFrontUrl = outputs.HmsCloudFrontUrl ?? `https://${distributionDomain}`;
  const assetBucket = outputs.HmsAssetBucketName ?? "hms-asset-bucket";
  const tableName = outputs.HmsTableName ?? "HmsSingleTable";

  return [
    "# Sri Lanka HMS Platform — Auto-Generated Frontend Environment",
    "# Generated by packages/cdk/scripts/export-outputs.mjs",
    `VITE_AWS_REGION=${region}`,
    `VITE_APPSYNC_URL=${graphqlUrl}`,
    `VITE_GRAPHQL_ENDPOINT=${graphqlUrl}`,
    `VITE_APPSYNC_API_ID=${graphqlApiId}`,
    `VITE_USER_POOL_ID=${userPoolId}`,
    `VITE_USER_POOL_CLIENT_ID=${userPoolClientId}`,
    `VITE_WEBHOOKS_INGRESS_URL=${webhooksUrl}`,
    `VITE_CLOUDFRONT_DOMAIN=${distributionDomain}`,
    `VITE_CLOUDFRONT_URL=${cloudFrontUrl}`,
    `VITE_ASSET_BUCKET_NAME=${assetBucket}`,
    `VITE_DYNAMODB_TABLE_NAME=${tableName}`,
  ];
}

/**
 * Writes environment lines to target file path.
 * @param {string} targetPath
 * @param {string[]} lines
 */
function writeEnvFile(targetPath, lines) {
  const parentDir = dirname(targetPath);
  if (!existsSync(parentDir)) {
    mkdirSync(parentDir, { recursive: true });
  }

  const content = `${lines.join("\n")}\n`;
  writeFileSync(targetPath, content, "utf-8");
  process.stdout.write(`Wrote environment configuration to: ${targetPath}\n`);
}

function main() {
  const config = resolveConfig();
  const outputs = loadOutputs(config.outputsPath);
  const lines = generateEnvLines(outputs, config.region);

  const envLocalPath = resolve(config.frontendDir, ".env.local");
  const envProductionPath = resolve(config.frontendDir, ".env.production");

  writeEnvFile(envLocalPath, lines);
  writeEnvFile(envProductionPath, lines);

  process.stdout.write(
    "Successfully exported CloudFormation outputs to frontend environment files.\n",
  );
}

main();
